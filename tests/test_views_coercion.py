def _containers(value, path=()):
    """Every nested dict or list below the top level, as a path of keys and indexes. Only a list's first row is
    replaced or entered: the later rows share its shape and are there for the row filters."""
    items = value.items() if isinstance(value, dict) else enumerate(value[:1]) if isinstance(value, list) else ()
    for key, child in items:
        if isinstance(child, dict | list):
            yield (*path, key)
            yield from _containers(child, (*path, key))


def _replaced(value, path, wrong):
    value = copy.deepcopy(value)
    target = value
    for key in path[:-1]:
        target = target[key]
    target[path[-1]] = wrong
    return value


def _variants(value):
    """The well-formed value, each nested container replaced in turn (string, int, None by turns), and top-level
    values of the wrong type."""
    yield "well_formed", value
    for index, path in enumerate(_containers(value)):
        wrong = WRONG[index % len(WRONG)]
        yield f"{'.'.join(map(str, path))}={wrong!r}", _replaced(value, path, wrong)
    for wrong in (*WRONG, [] if isinstance(value, dict) else {}):
        yield f"top={wrong!r}", wrong


def _case(name, function, *args, vary=(0,), **kwargs):
    cases = {}
    for position in vary:
        for label, value in _variants(args[position]):
            call_args = (*args[:position], value, *args[position + 1:])
            cases[f"{name}[{position}:{label}]"] = (function, call_args, kwargs)
    return cases


